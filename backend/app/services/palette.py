"""Цвета спикеров.

Подобраны так, чтобы читаться и на светлой, и на тёмной теме и
различаться при самых частых видах цветовой слепоты.
"""

SPEAKER_COLORS: list[str] = [
    "#2563eb",  # синий
    "#e11d48",  # малиновый
    "#059669",  # зелёный
    "#d97706",  # янтарный
    "#7c3aed",  # фиолетовый
    "#0891b2",  # бирюзовый
    "#be185d",  # пурпурный
    "#4d7c0f",  # оливковый
    "#b45309",  # охра
    "#4f46e5",  # индиго
]


def color_for(index: int) -> str:
    return SPEAKER_COLORS[index % len(SPEAKER_COLORS)]


def default_name(index: int) -> str:
    return f"Спикер {index + 1}"
